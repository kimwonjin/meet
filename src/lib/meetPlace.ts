export type Place = { location?: string | null; district?: string | null };

const dist2 = (a: LatLng, b: LatLng) => (a[0] - b[0]) ** 2 + ((a[1] - b[1]) * 0.8) ** 2; // 경도 1도가 위도보다 짧다

// 두 사람에게 편한 동네 이름 (모르면 null)
export function suggestMeetArea(a: Place, b: Place): string | null {
  const ca = a.district ? CENTER[a.district] : undefined;
  const cb = b.district ? CENTER[b.district] : undefined;
  if (ca && cb) {
    const mid: LatLng = [(ca[0] + cb[0]) / 2, (ca[1] + cb[1]) / 2];
    let best = HUBS[0];
    for (const h of HUBS) if (dist2(mid, h.at) < dist2(mid, best.at)) best = h;
    return best.name;
  }
  // 구·시를 모르면: 같은 지역이면 그 지역 중심가, 아니면 추천하지 않는다
  if (a.location && a.location === b.location) {
    if (a.location === '서울') return '강남역·홍대입구 같은 서울 중심가';
    if (a.location === '경기') return null;
    return `${a.location} 중심가`;
  }
  return null;
}

export const MEET_TIP = '첫 만남은 사람이 많은 카페에서 1~2시간을 추천해요';

// 연락처 메시지·홈 카드에 붙이는 한 줄
export function meetPlaceLine(a: Place, b: Place): string | null {
  const area = suggestMeetArea(a, b);
  return area ? `📍 두 분이 오가기 편한 곳: ${area} 주변` : null;
}
