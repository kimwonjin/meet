// 동의 기록 저장
export async function recordConsents(userId: string, docs: string[]) {
  const { error } = await supabase
    .from('user_consents')
    .insert(docs.map((doc) => ({ user_id: userId, doc, version: TERMS_VERSION })));
  if (error) console.error('recordConsents error:', error);
  return { error };
}
